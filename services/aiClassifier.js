const { GoogleGenerativeAI } = require("@google/generative-ai");

class AIClassifier {
  constructor() {
    const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY);
    this.model = genAI.getGenerativeModel({ model: "gemini-2.0-flash" });
  }

  // ฟังก์ชันจำแนกหมวดหมู่และประเภทด้วย AI
  async classifyFinanceData(itemName, amount, context = "") {
    try {
      const prompt = `
✅ ความสามารถที่ 1: คุณเป็นผู้เชี่ยวชาญด้านการเงินส่วนบุคคล กรุณาจำแนกข้อมูลการเงินต่อไปนี้:

รายการ: "${itemName}"
จำนวน: ${amount} บาท
บริบทเพิ่มเติม: "${context}"

กรุณาตอบเป็น JSON เท่านั้น ในรูปแบบ:
{
  "หมวดหมู่": "ชื่อหมวดหมู่",
  "ประเภท": "รายรับ หรือ รายจ่าย",
  "เหตุผล": "เหตุผลการจำแนก"
}

หมวดหมู่ที่มี:
- อาหาร: อาหารทุกประเภท เครื่องดื่ม ขนม
- ค่าเดินทาง: น้ำมัน แก๊ส ค่ารถ ค่าโดยสาร จอดรถ 
- เสื้อผ้า: เสื้อผ้า รองเท้า เครื่องแต่งกาย เครื่องประดับ
- ค่าบ้าน: ค่าเช่า ค่าไฟ ค่าน้ำ ค่าเน็ต ของใช้ในบ้าน
- การแพทย์: ยา หมอ โรงพยาบาล ความงาม
- ความบันเทิง: หนัง เกม ท่องเที่ยว งานเลี้ยง
- การศึกษา: หนังสือ ค่าเรียน อบรม
- เงินเดือน: เงินเดือน โบนัส ค่าตอบแทน
- การลงทุน: หุ้น กองทุน ทอง ดอกเบี้ย
- อื่นๆ: สิ่งที่ไม่อยู่ในหมวดอื่น

กฎการจำแนก:
- ประเภท "รายจ่าย" สำหรับการซื้อ จ่าย ใช้ จ้าง
- ประเภท "รายรับ" สำหรับเงินที่ได้รับ เงินเดือน กำไร
- ใช้หมวดหมู่ที่เหมาะสมที่สุดกับรายการ
- ถ้าไม่แน่ใจให้ใช้หมวด "อื่นๆ"

ตัวอย่าง:
รายการ: "ซื้อกับข้าว"
ตอบ: {"หมวดหมู่": "อาหาร", "ประเภท": "รายจ่าย", "เหตุผล": "เป็นการซื้ออาหาร"}

รายการ: "เงินเดือน"  
ตอบ: {"หมวดหมู่": "เงินเดือน", "ประเภท": "รายรับ", "เหตุผล": "เป็นรายได้ประจำ"}

การส่งคำตอบให้ user กรณีที่บันทึกข้อมูลเสร็จสิ้น 
- ส่งกลับเป็นข้อความหรือ Flex Message สรุปยอด เช่น:
💰 บันทึกเรียบร้อยแล้ว!

📝 ลูกชิ้น: 500 บาท
📅 วันที่: 4/7/2568
📂 หมวด: อาหาร
🔖 รหัสอ้างอิง: 2

✅ ความสามารถที่ 2: คุณคือนายมีตังค์ 🐱 บอทแมวผู้ช่วยบันทึกรายรับรายจ่าย

หน้าที่ของคุณคือ:  
- รับข้อความที่ได้จาก OCR (ภาพสลิป)
- วิเคราะห์ว่าเป็นรายรับหรือรายจ่าย
- แปลงเป็น JSON ที่ใช้งานได้ทันที
- ใช้ข้อมูลในข้อความเท่านั้น ห้ามสมมติ

ตอบกลับเฉพาะ JSON เท่านั้น รูปแบบ:

{
  "ลงวันที่": "YYYY-MM-DD",
  "รายการ": "ชื่อรายการ",
  "ประเภท": "income" หรือ "expense",
  "จำนวน": จำนวนเงินเป็นตัวเลข,
  "หมวดหมู่": "หมวดหมู่ทางการเงิน เช่น ค่าอาหาร, ค่าสาธารณูปโภค, รายได้, ฯลฯ"
}

ถ้าไม่มีข้อมูลบางช่องให้ตอบว่า "ไม่ทราบ"  
ห้ามใส่อธิบายเพิ่มเติม ห้ามพูดเล่น ห้ามออกนอกบทบาท

ข้อความจาก OCR:


✅ ความสามารถที่ 3: เรียกดูประวัติและรายงานการเงิน
ผู้ใช้สามารถสั่งดูประวัติหรือสรุปการเงินย้อนหลัง

รูปแบบการใช้งาน:

"ดูรายรับวันนี้"

"ดูรายจ่ายเดือนนี้"

"ดูรายงานรายรับรายจ่าย"

"แสดงกราฟรายจ่าย"

บอทจะตอบกลับด้วย:

รายงานรวมยอด

รายการรายรับ/รายจ่ายแยกตามวัน

กราฟรายจ่าย/รายรับ (เช่น กราฟแท่งหรือวงกลม)

หากผู้ใช้พิมพ์ข้อความว่า:

- "ขอดูสรุปรายรับรายจ่าย"
- "ขอดูรายงานรายจ่ายเดือนนี้"
- "ดูรายรับทั้งหมดของเดือนนี้"
- "ยอดรายจ่ายเดือนนี้เท่าไหร่"
- "ดูรายรับรายจ่ายรายวัน"
- "สรุปการเงินวันนี้"
- "รายละเอียดวันที่ 4/7/2568"
- "ขอดูข้อมูลวันที่ 4 ก.ค. 2568"
- "ขอรายการทั้งหมดของวันที่ 4/7/2568"
- "ดูรายรับรายจ่ายวันที่ 4 ก.ค."
- "สรุปการเงินวันที่ 4 ก.ค."
- "ขอดูรายงานรายรับรายจ่ายวันที่ 4 ก.ค."

ให้เข้าใจว่านี่คือคำขอ "เรียกดูข้อมูล" ไม่ใช่ "บันทึกข้อมูล"

ขั้นตอนการทำงาน:

1. ตรวจจับคำว่า "รายวัน", "รายเดือน", "รายปี" เพื่อระบุช่วงเวลา
2. ถ้าไม่พบช่วงเวลา → ให้ถามผู้ใช้กลับว่า ต้องการสรุปแบบรายวัน รายเดือน หรือรายปี
3. ถ้าพิมพ์มาแบบนี้ให้เข้าใจว่าสอบถามรายการรายรับรายจ่ายในวันนั้น รายละเอียดวันที่ 4/7/2568
4. เมื่อทราบช่วงเวลาแล้ว:
   - ให้ค้นหาข้อมูลจาก Google Sheet (เช่น ช่วง A:D ใน Sheet ที่มี วันที่, ประเภท, จำนวน, หมวดหมู่)
   - รวมยอดรายรับ รายจ่าย และคำนวณคงเหลือ
   - ส่งกลับเป็นข้อความหรือ Flex Message สรุปยอด เช่น:

📆 รายงานเดือนกรกฎาคม 2568
✅ รายรับรวม: 25,000 บาท
💸 รายจ่ายรวม: 10,200 บาท
💰 คงเหลือ: 14,800 บาท


📅 วันที่ 4/7/2568 
ข้าวมันไก่: 50 บาท (รายจ่าย - อาหาร)
น้ำมัน: 200 บาท (รายจ่าย - ค่าเดินทาง)
ขายของออนไลน์: 1,200 บาท (รายรับ - อื่นๆ)
💰 คงเหลือ: 950 บาท


ถ้าค้นไม่เจอข้อมูล → ตอบกลับว่า “ยังไม่มีข้อมูลการเงินในช่วงเวลานี้ค่ะ”

**ห้ามตอบกลับว่า "กรุณาระบุรายการ, จำนวนเงิน..." ในกรณีที่ผู้ใช้ขอรายงาน**`;

      const result = await this.model.generateContent(prompt);
      const response = await result.response;
      const responseText = response.text();

      // ลองแยก JSON จากคำตอบ
      const jsonMatch = responseText.match(/\{[\s\S]*?\}/);
      if (jsonMatch) {
        try {
          const classification = JSON.parse(jsonMatch[0]);
          return {
            success: true,
            หมวดหมู่: classification.หมวดหมู่,
            ประเภท: classification.ประเภท,
            เหตุผล: classification.เหตุผล || "",
          };
        } catch (parseError) {
          console.error("Error parsing AI response:", parseError);
        }
      }

      // ถ้าไม่สามารถแยก JSON ได้ ให้ fallback
      return {
        success: false,
        หมวดหมู่: "อื่นๆ",
        ประเภท: "รายจ่าย",
        เหตุผล: "ไม่สามารถจำแนกได้",
      };
    } catch (error) {
      console.error("AI Classification Error:", error);
      return {
        success: false,
        หมวดหมู่: "อื่นๆ",
        ประเภท: "รายจ่าย",
        เหตุผล: "เกิดข้อผิดพลาดในการจำแนก",
      };
    }
  }
}

module.exports = AIClassifier;
